-- 1. headache_logs テーブルの作成
CREATE TABLE IF NOT EXISTS headache_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    event_time TIMESTAMP WITH TIME ZONE NOT NULL,
    location_name TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    pain_level INTEGER CHECK (pain_level >= 0 AND pain_level <= 10),
    factors TEXT[], -- 配列型
    memo TEXT,
    pressure_current NUMERIC(6, 2),
    pressure_delta_3h NUMERIC(5, 2),
    pressure_trend TEXT,
    meta_data JSONB -- その他の計算値を格納
);

-- 2. RLS (Row Level Security) の設定
-- 開発用として、ひとまず全ての操作を許可します（本番運用時は認証ユーザーのみに制限することを推奨）
ALTER TABLE headache_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Enable all access for all users" ON headache_logs
    FOR ALL
    USING (true)
    WITH CHECK (true);

-- 3. インデックスの作成（クエリ高速化）
CREATE INDEX IF NOT EXISTS idx_headache_logs_event_time ON headache_logs(event_time);
